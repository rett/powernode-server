class NodeModulesController < ApplicationController
  load_resource except: [:create]
  authorize_resource

  before_action { add_breadcrumb @node_module if @node_module.try(:persisted?) }
  before_action :load_objects, only: [:create, :edit, :new, :update]

  respond_to :html, :json

  def index
    @search = @node_modules.subscription_variety.search(params[:q])
    @node_modules = @search.result.paginate(page: params[:page], per_page: params[:per_page])
    respond_with @node_modules
  end

  def show
    @details = @node_module.details
    respond_with @node_module
  end

  def new
    respond_with @node_module
  end

  def create
    @node_module = NodeModule.create(node_module_params.merge({ account_id: @current_account.id }))
    respond_with @node_module
  end

  def update
    @node_module.update_attributes(node_module_params)
    respond_with @node_module
  end

  def destroy
    @node_module.destroy
    respond_with @node_module
  end

  def dependency_tree
    tree = {}
    tree[:nodes] = []
    tree[:links] = []
    module_list = [@node_module, @node_module.dependant_modules_with_recursion].flatten
    module_list.each_with_index { |m, i| tree[:nodes] << { index: i, id: m.id, name: m.name, group: m.node_module_category_id } }
    tree[:nodes].each do |n|
      source = n[:index]
      module_list.find { |m| m.id == n[:id] }.dependant_modules.each do |d|
        target = tree[:nodes].find { |t| t[:id] == d[:id] }.try(:[], :index)
        tree[:links] << { source: source, target: target } if target
      end
    end
    render json: tree.to_json
  end

  def download
    respond_to do |format|
      format.html do
        if can?(:manage, NodeModule) && @node_module.ready?
          send_file(@node_module.data.path, type: 'application/octet-stream', filename: @node_module.data_file_name)
        else
          render nothing: true, status: :not_found
        end
      end
    end
  end

  def update_platform_items
    if (node_platform =  NodePlatform.find_by(id: params[:node_platform_id]))
      @available_node_templates = node_platform.node_templates.accessible_by(@current_ability, :update)
      @available_node_modules = node_platform.node_modules.accessible_by(@current_ability, :use).subscription_variety.where.not(id: @node_module.try(:id))
    else
      @available_node_templates = []
      @available_node_modules = []
    end
  end

  private

  def load_objects
    @available_build_scripts = NodeScript.accessible_by(@current_ability, :use).build_variety
    @available_node_modules = @node_module.try(:node_platform) ? @node_module.node_platform.node_modules.accessible_by(@current_ability, :use).subscription_variety.where.not(id: @node_module.try(:id)) : []
    @available_node_platforms = NodePlatform.accessible_by(@current_ability, :use)
    @available_node_templates = @node_module.try(:node_platform) ? @node_module.node_platform.node_templates.accessible_by(@current_ability, :update) : []
    @available_puppet_modules = PuppetModule.accessible_by(@current_ability, :use)
    @available_node_module_categories = NodeModuleCategory.accessible_by(@current_ability, :use)
  end

  def node_module_params
    permitted_params  = [{ node_template_ids: [],
                           puppet_module_ids: [] },
                         :build_script_id,
                         :configurable,
                         :custom_build_script,
                         :data,
                         :dependency_spec,
                         :description,
                         :details,
                         :enabled,
                         :immutable,
                         :init_restart,
                         :init_start,
                         :init_stop,
                         :lock_spec,
                         :mask,
                         :name,
                         :node_platform_id,
                         :node_module_category_id,
                         :package_spec,
                         :priority,
                         :provisional,
                         :required,
                         :reboot_required,
                         :spec]
    permitted_params += [:public] if can?(:manage, NodeModule)
    permitted_params += [{ dependant_module_ids: [] }] if can?(:create, NodeModuleDependency)
    params.require(:node_module).permit(*permitted_params)
  end
end
